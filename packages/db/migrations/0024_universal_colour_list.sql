-- The 44 already here are mostly web colour names typed by hand and mostly
-- without a hex, which is why the swatch beside a colour was usually missing.
-- This is the full CSS named-colour set, the one every browser, design tool
-- and storefront theme already agrees on, with its hex codes.
--
-- Nothing is removed. The eight SLK added that are not web colours — Bottle
-- Green, Cream, Golden, Multicolour, Mustard, Off White, Peach, Rust — keep
-- their own hex and their place in the list. They are the ones a weaver
-- actually says, and a standard list is no reason to lose them.
--
-- Existing rows are matched by name and only gain a hex where they had none,
-- so nothing already chosen on a record is disturbed and no colour moves.

